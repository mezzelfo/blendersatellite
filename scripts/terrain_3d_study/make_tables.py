"""Markdown tables of the step-20 study from its JSON outputs (no new measurement).

  python -I make_tables.py --study STUDY > STUDY/tables.md
"""
import argparse
import json
import re
from pathlib import Path


def gnu_time(path):
    text = Path(path).read_text()
    wall = re.search(r'Elapsed \(wall clock\) time \(h:mm:ss or m:ss\): (\S+)', text).group(1)
    rss = int(re.search(r'Maximum resident set size \(kbytes\): (\d+)', text).group(1))
    return wall, rss / 1e6


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


def f(x, n=2):
    return '—' if x is None else f'{x:,.{n}f}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--study', type=Path, required=True)
    S = parser.parse_args().study
    blocks = json.loads((S / 'blocks.json').read_text())
    summary = json.loads((S / 'summary.json').read_text())
    analysis = {p.stem: json.loads(p.read_text()) for p in (S / 'analysis').glob('*.json')}
    metrics = json.loads((S / 'compare' / 'metrics.json').read_text())
    print('# Step 20 tables (generated by make_tables.py)\n')

    print('## Block choice\n')
    rows = []
    for name, b in blocks['blocks'].items():
        for r in b['per_tile']:
            rows.append([name, r['tile'], f(r['archive_bytes'] / 1e6, 1), f"{r['faces']:,}", f(r['covered_fraction'], 4)])
        rows.append([f'**{name} total**', '', f(b['archive_bytes'] / 1e6, 1), f"{b['faces']:,}", ''])
    print(table(['block', 'tile', 'archive MB', 'faces (log.jsonl)', 'covered fraction'], rows))
    print(f"Total archives: {blocks['total_archive_bytes'] / 1e9:.3f} GB (STOP limit 15 GB). SUBURB candidates "
          f"(complete 3 x 3, all covered > 0.98): {blocks['suburb_candidates']}, with known face counts: "
          f"{blocks['suburb_eligible']}. Lowest five: {blocks['suburb_ranking'][:5]}\n")

    print('## A.1 Archive contents\n')
    rows = []
    for t in sum((b['tiles'] for b in blocks['blocks'].values()), []):
        a = analysis[t]['A1']
        e = a['by_extension']
        rows.append([t, e.get('.obj', 0), e.get('.mtl', 0), e.get('.jpg', 0), sum(v for k, v in e.items() if k not in ('.obj', '.mtl', '.jpg')),
                     ','.join(a['folders']), ','.join(f'{k}:{v}' for k, v in a['texture_tile_level_fields'].items()),
                     sum(len(v) for v in a['lod_name_hits'].values()), f(a['uncompressed_bytes'] / 1e6, 0)])
    print(table(['tile', 'OBJ', 'MTL', 'JPG', 'other', 'folder', 'Tile-x-y-a-b fields a-b', 'L##/LOD/level name hits', 'unzipped MB'], rows))

    print('## A.2 Vertices, faces, textures, texel\n')
    rows = []
    for t in sum((b['tiles'] for b in blocks['blocks'].values()), []):
        a = analysis[t]['A2']
        sizes = ', '.join(f'{k}:{v}' for k, v in sorted(a['texture_sizes'].items(), key=lambda kv: -int(kv[0].split('x')[0])))
        rows.append([t, f"{a['vertices']:,}", f"{a['faces']:,}", a['textures'], sizes, f(a['texture_megapixels'], 0),
                     f(a['texel_m_median'] * 100, 2), f(a['texel_m_p5_p95'][0] * 100, 2) + '–' + f(a['texel_m_p5_p95'][1] * 100, 2)])
    print(table(['tile', 'vertices', 'faces', 'textures', 'texture sizes (px: count)', 'texture MP', 'texel median cm', 'texel p5–p95 cm'], rows))

    print('## A.3 Geometry\n')
    rows = []
    for t in sum((b['tiles'] for b in blocks['blocks'].values()), []):
        a = analysis[t]['A3']
        e = a['edge_m_percentiles']
        rows.append([t, f(e['1'], 3), f(e['5'], 3), f(e['25'], 3), f(e['50'], 3), f(e['75'], 3), f(e['95'], 3), f(e['99'], 3), f(a['edge_m_max'], 1),
                     f(a['vertical_face_fraction'], 3), f(a['vertical_area_fraction'], 3), f"{a['uv_islands']:,}", f(a['faces_per_uv_island'], 1)])
    print(table(['tile', 'edge p1', 'p5', 'p25', 'p50', 'p75', 'p95', 'p99', 'max (m)', 'vertical faces', 'vertical area', 'UV islands', 'faces/island'], rows))

    print('## B. Variants: cost and geometric error (per block)\n')
    rows = []
    for name, b in summary['blocks'].items():
        for v, x in b['variants'].items():
            h = x.get('hausdorff', {})
            build = x.get('build_wall_s_sum', x.get('build_wall_s'))
            rows.append([name, v, f"{x['triangles']:,}", f(x['texture_megapixels'], 1), f(x['disk_zipped_bytes'] / 1e6, 1),
                         f(x['faces_over_target'], 3) if 'faces_over_target' in x else '—',
                         f(build, 0) if build is not None else '—', f(x.get('build_peak_rss_gb'), 2) if x.get('build_peak_rss_gb') else '—',
                         f(h.get('mean_m'), 3), f(h.get('p95_m'), 3), f(h.get('max_m'), 2)])
    print(table(['block', 'variant', 'triangles', 'texture MP', 'disk zipped MB', 'faces / target', 'build s (sum of tiles)',
                 'peak RSS GB', 'Hausdorff mean m', 'p95 m', 'max m'], rows))

    print('## B. DEC per tile\n')
    rows = []
    for name, b in summary['blocks'].items():
        for r in (4, 16, 64):
            for p in b['variants'][f'DEC_{r}']['per_tile']:
                rows.append([name, r, p['tile'], f"{p['ref_faces']:,}", f"{p['target']:,}", f"{p['faces']:,}", f(p['faces_over_target'], 3),
                             f(p['build_wall_s'], 0), f(p['build_peak_rss_gb'], 2), f(p['texture_megapixels'], 2), p['faces_bad_uv'],
                             f(p['uv_stretch_area_gt4'], 3), f(p['hausdorff']['mean_m'], 3), f(p['hausdorff']['p95_m'], 3), f(p['hausdorff']['max_m'], 2)])
    print(table(['block', 'r', 'tile', 'REF faces', 'target', 'faces', 'faces/target', 'build wall s', 'peak RSS GB', 'texture MP',
                 'faces bad UV', 'area UV stretch >4x', 'H mean m', 'H p95 m', 'H max m'], rows))

    print('## Renders: cost\n')
    rows = []
    for r in summary['renders']:
        rows.append([r['block'], r['variant'], r['gpu'], f"{r['triangles']:,}" if r['triangles'] else '—', f(r['texture_megapixels'], 1),
                     r['materials'], r['gpu_peak_minus_baseline_mib'], r['gpu_baseline_mib'], f(r['setup_s'], 0), f(r['wall_s'], 0), f(r['peak_rss_gb'], 2),
                     f(sorted(r['render_s'])[len(r['render_s']) // 2], 1) if r['render_s'] else '—'])
    print(table(['block', 'variant', 'nvidia-smi GPU', 'triangles', 'texture MP', 'materials', 'GPU peak - baseline MiB', 'baseline MiB',
                 'setup s', 'wall s', 'peak RSS GB', 'median s per image'], rows))
    m = summary['gpu_model']
    print(f"GPU model ({m['points']} renders, censored excluded): MiB = {m['m0_mib']:.0f} + {m['mib_per_million_triangles']:.1f} x Mtriangles "
          f"+ {m['mib_per_texture_megapixel']:.2f} x texture MP + {m['mib_per_thousand_materials']:.1f} x kmaterials; max |residual| "
          f"{m['residual_max_abs_mib']:.0f} MiB. Censored: {m['censored']}\n")

    for title, views in (('C.3 Image metrics against REF (580 mm)', None), ('C.5 Half GSD (1160 mm, theta 15 N)', ['t15_N_hr'])):
        print(f'## {title}\n')
        rows = []
        for r in metrics:
            if (views is None and r['view'] == 't15_N_hr') or (views is not None and r['view'] not in views):
                continue
            a, v = r['all'], r['vertical']
            rows.append([r['block'], r['view'], r['variant'], f(r['vertical_fraction'], 3), f(a['mean_abs_dRGB_DN'], 2), f(a['psnr_db'], 2),
                         f(a['ssim_luma'], 4), '%+.2f, %+.2f' % tuple(a['shift_rows_cols_px']), f(a['variant_transparent_fraction'], 4),
                         f(v.get('mean_abs_dRGB_DN'), 2), f(v.get('psnr_db'), 2), f(v.get('ssim_luma'), 4),
                         '%+.2f, %+.2f' % tuple(v['shift_rows_cols_px']) if 'shift_rows_cols_px' in v else '—'])
        print(table(['block', 'view', 'variant', 'vertical px fraction', '|dRGB| DN', 'PSNR dB', 'SSIM', 'shift r, c px',
                     'transparent', 'vert |dRGB|', 'vert PSNR', 'vert SSIM', 'vert shift'], rows))

    print('## D. Extrapolation\n')
    e = summary['extrapolation']
    t = e['melbourne_570']
    print(f"570 tiles: {t['archive_bytes'] / 1e9:.2f} GB of archives, {t['ref_faces'] / 1e6:.1f} M REF faces "
          f"(faces of {', '.join(t['faces_estimated_for'])} estimated from their archive size), {t['area_km2']:.2f} km^2. "
          f"375 km^2 = x {e['scene_375km2']['scale_from_570']:.3f} ({e['scene_375km2']['assumption']}).\n")
    rows = []
    for v, x in e['variants'].items():
        for src, row in x['estimates'].items():
            for case, r in row.items():
                rows.append([v, src.replace('ratios_from_', ''), case, f(r['triangles'] / 1e6, 1), f(r['texture_megapixels'], 0),
                             f(r['materials'] / 1e3, 0), f(r['disk_bytes'] / 1e9, 2), f(r['build_cpu_s'] / 3600, 1), r['build_workers'],
                             f(r['build_wall_s'] / 3600, 2), f(r['gpu_mib'] / 1024, 1), 'yes' if r['fits_12gb'] else 'no'])
    print(table(['variant', 'ratios from', 'case', 'Mtriangles', 'texture MP', 'kmaterials', 'disk GB', 'build CPU h', 'workers',
                 'build wall h', 'GPU GiB (model)', 'fits 12 GB'], rows))


if __name__ == '__main__':
    main()
